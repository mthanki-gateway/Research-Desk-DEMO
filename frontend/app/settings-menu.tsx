"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";
import { Ripplable } from "./md";

/**
 * The Settings entry at the bottom of the drawer.
 *
 * A plain link now. Its sections (API keys, Feature access, Profile) live in
 * a menu down the left of the Settings page itself, where they stay visible
 * while you work -- a popup menu hid them the moment you picked one.
 */
export default function SettingsMenu() {
  const pathname = usePathname();
  return (
    <Ripplable
      as={Link}
      href="/settings"
      prefetch
      className="md-nav-item w-full"
      data-active={pathname.startsWith("/settings")}
    >
      <span className="md-nav-icon">
        <GearGlyph />
      </span>
      Settings
    </Ripplable>
  );
}

